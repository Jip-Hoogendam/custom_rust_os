use core::{
    arch::{self, asm},
    fmt::Display,
};

use spin::MutexGuard;

use crate::{
    interrupts::interupt_gaurd::{InteruptController, InteruptGaurd},
    tables::{
        DiscriptorTables,
        gdt::SegmentSelector,
        idt::{InteruptDiscriptor, InteruptDiscriptorIndex},
    },
};

/// This holds the current stack frame of the interuptt
#[repr(C)]
pub struct InterruptStackFrame {
    pub ip: usize,
    pub cs: usize,
    pub flags: usize,
    pub sp: usize,
    pub ss: usize,
}

impl Display for InterruptStackFrame {
    #![allow(clippy::cast_possible_truncation)]
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            f,
            "[STACK_FRAME]\nip:\t\t{:#x}\ncs:\t\t{}\nflags:\t\t{:#x},\nsp:\t\t{:#x}, \nss:\t\t{}",
            self.ip,
            SegmentSelector::from(self.cs as u16),
            self.flags,
            self.sp,
            SegmentSelector::from(self.ss as u16)
        )
    }
}

/// Fault interutps are interupts that get generated by the cpu when there is a programming fault.
mod fault;
pub mod interupt_gaurd;
/// IO interupts are interupts that get created via io devices like the I/O APIC or keybords or mouse.
mod io;
/// System interutps are interutps defined by the system. These mostly include kernal call interupts
/// or timer interupt handdelers.
mod system;

/// Loads the interupts into the `DiscriptorTables`.
///
/// # Panics
/// This function panics if the tss contains too many `InterruptStackFrame`s
pub fn load_interupts<T>(
    dt: &mut MutexGuard<DiscriptorTables>,
    selector: SegmentSelector,
    interupt_gaurd: &InteruptGaurd<T>,
) where
    T: InteruptController,
{
    use crate::variables::InteruptStack;
    static DOUBLE_FAULT_STACK: InteruptStack = [0u8; _];
    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::PageFault,
        InteruptDiscriptor::new_trap(fault::page_fault_handeler as *const (), selector),
        interupt_gaurd,
    );
    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::Breakpoint,
        InteruptDiscriptor::new_trap(system::breakpoint_handler as *const (), selector),
        interupt_gaurd,
    );

    let double_fault_stack = dt
        .get_mut_tss()
        .push_ist(&raw const DOUBLE_FAULT_STACK as u64)
        .expect("Too many interupt stacks allocated");

    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::DoubleFault,
        InteruptDiscriptor::new_trap(fault::double_fault_handler as *const (), selector)
            .set_stack(double_fault_stack),
        interupt_gaurd,
    );

    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::TaskSwitch,
        InteruptDiscriptor::new_interupt(system::task_switch as *const (), selector),
        interupt_gaurd,
    );

    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::TaskKill,
        InteruptDiscriptor::new_interupt(system::task_kill as *const (), selector),
        interupt_gaurd,
    );

    dt.get_mut_idt().set_discriptor(
        InteruptDiscriptorIndex::Keyboard,
        InteruptDiscriptor::new_interupt(io::keyboard_interrupt_handler as *const (), selector),
        interupt_gaurd,
    );
}

#[inline]
pub extern "C" fn call_kill() -> ! {
    unsafe {
        asm! {"int {x}", x = const(InteruptDiscriptorIndex::TaskKill as u8) ,options(nomem, nostack, noreturn) }
    }
}

#[inline]
pub extern "C" fn call_switch_task() {
    unsafe {
        asm! {"int {x}", x = const(InteruptDiscriptorIndex::TaskSwitch as u8) ,options(nomem, nostack) }
    }
}

